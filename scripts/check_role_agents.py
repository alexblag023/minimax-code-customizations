
#!/usr/bin/env python3
"""Check the router's role agents for style, response contract, and icons.

Run: python -X utf8 scripts/check_role_agents.py [--profile PATH]
Exit code: 0 - all checks pass; 1 - violations found.

Checks (for each of the role agents in the catalog agents/<role>/):
1. agent.md exists, is readable as UTF-8, and contains no NUL bytes.
2. Front matter: name matches the role name; description and displayName are present.
3. MCode house style: persona block, "# Role:" heading, "#" level sections
   (How You Work / Response Format / What You Must Not Do / When To Stop),
   "Return:" block at the end, body length within a broad sanity range.
4. Language: the body is in English; the response is in the user's language. The first
   line must contain the exact instruction; JSON keys are in English.
5. Machine contract: the response example parses as JSON; author roles require
   solution/assumptions/self_tests/risks/confidence; critic roles require
   reviews with cid/ac_results/defects/rubric; defects require location/claim/
   evidence/severity.
6. Icon: avatar.png next to the prompt, a valid PNG, and front matter contains
   avatar: avatar.png inside the x-mavis: block.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
AGENTS_DIR = REPO / "agents"
PROFILE_AGENTS = Path.home() / ".minimax" / "agents"

# Required router roles (authors and critics of the shared
# decision-review protocol): these roles require the contract.
# Remaining roles use the contract defined in their brief.
# 15.11.2026: набор сокращён с 36 ролей до 8 крупных с непересекающимися
# зонами. Авторский контракт (solution/...) и контракт критиков больше не
# применяются: у каждой новой роли свой контракт ответа в карточке.
AUTHOR = []
CRITIC = []
JUDGE = []
# Review roles: produce a verdict with findings, not a solution.
REVIEWER = ["review"]
FREE = ["search", "explain", "verify", "implement", "fix", "design", "document"]

# Роли, которые обязаны быть в каталоге агентов. Список зафиксирован здесь
# намеренно и НЕ выводится из каталога: иначе удаление каталога роли молча
# сокращало бы набор проверяемых агентов. Ролевой матрицы роль→модель нет
# (снята 15.11.2026) - источник истины о зонах ответственности карточки
# агентов (agents/<роль>/agent.md, поле "Use when:").
EXPECTED_ROLES = (
    "search", "explain", "review", "verify",
    "implement", "fix", "design", "document",
)

SECTIONS = ["# How You Work", "# Response Format", "# What You Must Not Do", "# When To Stop"]
LANG_LINE = "Respond in the user's language. All JSON keys must be strictly English, as in the schema below."
AUTHOR_KEYS = {"solution", "assumptions", "self_tests", "risks", "confidence"}
CRITIC_KEYS = {"cid", "ac_results", "defects", "rubric"}
DEFECT_KEYS = {"location", "claim", "evidence", "severity"}
# Since 18.11.2026 the review payload (findings, verdict) lives in the Markdown
# part of the answer, so the review role shares the common core like everyone else.
REVIEWER_KEYS = {"role", "confidence", "assumptions", "risks", "unverified"}
PNG_SIG = b"\x89PNG\r\n\x1a\n"

# Common response core (18.11.2026): the same machine tail in every role. The
# role's own payload lives in the Markdown part of the answer, the core holds
# metadata only.
CORE_KEYS = {"role", "confidence", "assumptions", "risks", "unverified"}

# Zone anchors: the rule has to stand in BOTH cards of a pair, otherwise the
# model that reads the other card sees no boundary and may take the task.
ZONE_ANCHORS = (
    ("search", "explain"),
    ("review", "verify"),
    ("fix", "implement"),
    ("design", "document"),
)


def png_ok(path: Path) -> str:
    """Validate a PNG: signature, chunk CRCs, color type, and decompressed IDAT length.

    Previously, role icons were generated by a script using color type 6 (RGBA),
    while pixels were written as 3-byte (RGB) values. The resulting file was
    corrupt: the signature was valid and the runtime returned 200, but the browser
    could not render the image, leaving the role without an icon. Therefore, check
    """
    import struct
    import zlib
    data = path.read_bytes()
    if not data.startswith(PNG_SIG):
        return "not a PNG"
    offset = 8
    idat = b""
    width = height = color_type = None
    while offset < len(data):
        if offset + 8 > len(data):
            return "truncated chunk header"
        length = struct.unpack(">I", data[offset:offset + 4])[0]
        ctype = data[offset + 4:offset + 8]
        payload = data[offset + 8:offset + 8 + length]
        if offset + 12 + length > len(data):
            return "truncated chunk payload"
        crc = struct.unpack(">I", data[offset + 8 + length:offset + 12 + length])[0]
        if crc != zlib.crc32(ctype + payload) & 0xFFFFFFFF:
            return "bad CRC in chunk %s" % ctype.decode("ascii", "replace")
        if ctype == b"IHDR":
            width, height, _depth, color_type = struct.unpack(">IIBB", payload[:10])
        if ctype == b"IDAT":
            idat += payload
        offset += 12 + length
    if width is None or not idat:
        return "no IHDR or IDAT"
    try:
        raw = zlib.decompress(idat)
    except zlib.error as exc:
        return "IDAT does not inflate: %s" % exc
    channels = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}.get(color_type)
    if channels is None:
        return "unknown color type %s" % color_type
    expected = height * (1 + width * channels)
    if len(raw) != expected:
        return ("IDAT holds %d bytes, expected %d for %dx%d color type %s"
                % (len(raw), expected, width, height, color_type))
    return ""

PROBLEMS: list[str] = []


def bad(role: str, msg: str) -> None:
    PROBLEMS.append("%s: %s" % (role, msg))


def json_examples(text: str) -> list:
    """Return all JSON objects in the Response Format section (fenced and unfenced)."""
    m = re.search(r"(?s)# Response Format(.*?)(?=\n# |\Z)", text)
    section = m.group(1) if m else text
    out = []
    for fenced in re.findall(r"(?s)" + chr(96) * 3 + r"json(.*?)" + chr(96) * 3, section):
        try:
            out.append(json.loads(fenced))
        except Exception:
            pass
    if not out:
        depth = 0
        start = None
        for i, ch in enumerate(section):
            if ch == "{":
                if depth == 0:
                    start = i
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0 and start is not None:
                    chunk = section[start:i + 1]
                    try:
                        out.append(json.loads(chunk))
                    except Exception:
                        pass
                    start = None
    return out


def english_keys(obj) -> bool:
    if isinstance(obj, dict):
        return all(isinstance(k, str) and k.isascii() for k in obj) and all(
            english_keys(v) for v in obj.values())
    if isinstance(obj, list):
        return all(english_keys(v) for v in obj)
    return True


def normalize_agent_text(text: str) -> str:
    """Normalize agent files for comparison.

    The MCode runtime rewrites agent files: it adds contextWindow, moves the
    description to the next line, and normalizes the model reference. These
    changes do not alter the role's content, so they are ignored when comparing
    the profile with the repository.
    """
    # Поля, которыми управляет рантайм и владелец в профиле (контекст,
    # закреплённая модель и её effort), в содержимом роли не участвуют: карточка
    # в профиле и в репозитории отличается ими и переносом строк.
    lines = [ln for ln in text.splitlines()
             if not re.match(r"^\s*(contextWindow|model|effort):", ln)]
    return re.sub(r"\s+", " ", " ".join(lines)).strip()


def expected_roles() -> set:
    """Roles that must exist in the agent catalog (see EXPECTED_ROLES).

    The list is fixed in the code, not read from the catalog: otherwise
    deleting a role directory would silently reduce the number of agents
    being checked.
    """
    return set(EXPECTED_ROLES)


def check_role(role: str, agents_dir: Path, profile_dir: Path) -> None:
    path = agents_dir / role / "agent.md"
    if not path.exists():
        bad(role, "agent.md file is missing")
        return
    raw = path.read_bytes()
    if b"\x00" in raw:
        bad(role, "file contains NUL bytes")
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        bad(role, "file is not UTF-8: %s" % exc)
        return

    if not re.search(r"(?m)^name:\s*" + re.escape(role) + r"\s*$", text):
        bad(role, "front matter is missing name: %s" % role)
    # The runtime parses the front matter as YAML. A plain scalar containing a
    # colon ("... Use when: ...") is invalid YAML, so the whole card is rejected
    # ("Agent configuration frontmatter is invalid"). Quoting the value fixes it.
    parts = text.split("---", 2)
    if len(parts) < 3:
        bad(role, "front matter block is missing")
    else:
        try:
            fm = yaml.safe_load(parts[1])
        except yaml.YAMLError as exc:
            bad(role, "front matter is not valid YAML: %s" % exc)
        else:
            if not isinstance(fm, dict):
                bad(role, "front matter is not a mapping")
    if not re.search(r"(?m)^description:\s*\S", text):
        bad(role, "missing description")
    else:
        # The role description is how the calling model selects a role (it sees
        # the registry through mavis_agent_list). Without an explicit selection
        # trigger, the role is indistinguishable from similar roles.
        # Триггер зоны ищем по ЗНАЧЕНИЮ поля description из разобранного YAML:
        # рантайм (и редактирование вручную) переносит длинное описание на
        # несколько строк, и проверка по первой строке давала бы ложное
        # замечание на корректной карточке.
        desc = ""
        parts = text.split("---", 2)
        if len(parts) >= 3:
            try:
                loaded = yaml.safe_load(parts[1]) or {}
                if isinstance(loaded, dict):
                    desc = str(loaded.get("description") or "")
            except yaml.YAMLError:
                desc = ""
        if not desc:
            desc = re.search(r"(?m)^description:\s*(.+)$", text).group(1).strip()
        if "Use when:" not in desc:
            bad(role, "description has no 'Use when:' trigger (cannot select the role by output type)")
    if not re.search(r"(?m)^\s*displayName:\s*\S", text):
        bad(role, "missing displayName")
    if "{{#if persona.enabled}}" not in text:
        bad(role, "missing persona block")
    if not re.search(r"(?m)^# Role:\s*\S", text):
        bad(role, "missing # Role: heading")
    for sec in SECTIONS:
        if sec not in text:
            bad(role, "missing section " + sec)
    if not re.search(r"(?m)^Return:", text):
        bad(role, "missing Return: block")
    body = text.split("---", 2)[-1]
    lines = len(body.splitlines())
    if not (40 <= lines <= 220):
        bad(role, "body is %d lines (expected 40-220)" % lines)
    if LANG_LINE not in text:
        bad(role, "missing response-language instruction")
    ru = len(re.findall(r"[\u0400-\u04FF]", body))
    if ru > 900:
        bad(role, "body is still in Russian (%d Cyrillic characters)" % ru)

    examples = json_examples(text)
    if not examples:
        bad(role, "Response Format has no parseable JSON example")
    else:
        for ex in examples:
            if not english_keys(ex):
                bad(role, "JSON example contains non-English keys")
        if role in AUTHOR:
            if not any(AUTHOR_KEYS <= set(ex) for ex in examples):
                bad(role, "missing author contract %s" % sorted(AUTHOR_KEYS))
        if role in CRITIC:
            ok = False
            for ex in examples:
                reviews = ex.get("reviews") if isinstance(ex, dict) else None
                if isinstance(reviews, list) and reviews:
                    item = reviews[0]
                    if isinstance(item, dict) and CRITIC_KEYS <= set(item):
                        defects = item.get("defects")
                        if isinstance(defects, list) and all(
                                isinstance(d, dict) and DEFECT_KEYS <= set(d) for d in defects):
                            ok = True
            if not ok:
                bad(role, "missing critic contract reviews[%s] with defects[] (list)" % sorted(CRITIC_KEYS))
        if role in REVIEWER:
            if not any(REVIEWER_KEYS <= set(ex) for ex in examples):
                bad(role, "missing review contract %s" % sorted(REVIEWER_KEYS))
        if role in JUDGE:
            if not any(isinstance(ex, dict) and "reviews" in ex for ex in examples):
                bad(role, "judge has no reviews")
        if not any(isinstance(ex, dict) and CORE_KEYS <= set(ex) for ex in examples):
            bad(role, "missing common response core %s" % sorted(CORE_KEYS))
        for ex in examples:
            if isinstance(ex, dict) and "confidence" in ex:
                if isinstance(ex["confidence"], bool) or not isinstance(
                        ex["confidence"], (int, float)):
                    bad(role, "confidence must be a number 0..1, got %r" % (
                        ex["confidence"],))

    # The machine tail must be announced: separator, role key, confidence.
    fmt = re.search(r"(?s)# Response Format(.*?)(?=\n# |\Z)", text)
    fmt_text = fmt.group(1) if fmt else ""
    if "---" not in fmt_text:
        bad(role, "Response Format does not define the machine tail separator")
    if "role" not in fmt_text:
        bad(role, "Response Format does not mention the role key of the machine tail")

    # icon
    icon = agents_dir / role / "avatar.png"
    if not icon.exists():
        bad(role, "missing avatar.png icon")
    else:
        problem = png_ok(icon)
        if problem:
            bad(role, "avatar.png is corrupt: %s" % problem)
    # The card declares the avatar the runtime serves: a content-addressed copy
    # next to the card (avatar-<hash>.png), while avatar.png in the repository is
    # the rendered source. Both must exist and carry the same bytes.
    xm = re.search(r"(?ms)^x-mavis:\r?\n((?:[ \t]+.*\r?\n)*)", text)
    declared = None
    if not xm:
        bad(role, "front matter is missing the x-mavis: block")
    else:
        am = re.search(r"(?m)^\s*avatar:\s*(\S+)\s*$", xm.group(1))
        if not am:
            bad(role, "front matter is missing avatar inside the x-mavis: block")
        else:
            declared = am.group(1).lstrip("./")
    if declared:
        served = agents_dir / role / declared
        if not served.exists():
            bad(role, "declared avatar %s is missing" % declared)
        else:
            problem = png_ok(served)
            if problem:
                bad(role, "declared avatar %s is corrupt: %s" % (declared, problem))
            if icon.exists() and served.read_bytes() != icon.read_bytes():
                bad(role, "declared avatar %s differs from the rendered avatar.png" % declared)
    # The profile copy is deliberately NOT checked. Since 16.11.2026 the roles
    # are built-in runtime agents, and a manual profile row with the same name
    # makes the runtime fail its startup seed (docs/native-role-agents.md).
    # The live delivery is the built-in asset, checked by check_card_asset_drift.


def check_card_asset_drift(agents_dir: Path, assets_dir: Path) -> None:
    """The installed prompt must equal the card body.

    The card is the source of truth, the asset is what the model receives. A
    silent difference means the role runs on a prompt nobody edited. Line
    endings are normalised: the builder writes LF, a checkout may hold CRLF.
    """
    if not assets_dir.is_dir():
        return
    config = REPO / "runtime" / "builtin-roles.json"
    if not config.is_file():
        return
    data = json.loads(config.read_text(encoding="utf-8"))
    for slot, spec in (data.get("slots") or {}).items():
        role = spec.get("role")
        card = agents_dir / str(role) / "agent.md"
        asset = assets_dir / slot / "system-prompt.md.hbs"
        if not card.is_file() or not asset.is_file():
            continue
        card_body = card.read_text(encoding="utf-8", errors="replace").split("---", 2)[-1]
        card_body = card_body.replace("\r\n", "\n").lstrip("\n")
        asset_body = asset.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")
        if card_body.strip() != asset_body.strip():
            bad(role, "installed prompt differs from the card (slot %s): run build_role_assets.py"
                % slot)


def check_zone_anchors(agents_dir: Path) -> None:
    """Every zone pair must be separated in BOTH cards.

    A rule that exists in one card only does not separate the roles: the model
    that reads the other card sees no boundary and may take the task.
    """
    bodies = {}
    for role in EXPECTED_ROLES:
        path = agents_dir / role / "agent.md"
        bodies[role] = (path.read_text(encoding="utf-8", errors="replace").lower()
                        if path.is_file() else "")
    for left, right in ZONE_ANCHORS:
        for role in (left, right):
            body = bodies.get(role, "")
            # The separating rule names both roles in one place: that line is
            # the boundary the model reads when it decides which role owns the
            # task. A card that only names its own role has no anchor.
            if not any(left in line and right in line for line in body.splitlines()):
                bad(role, "missing zone anchor that names %s and %s together" % (left, right))


def check_skill_channel() -> None:
    """The skill must pass the role as the bare agent name.

    When called with a plugin prefix (`<plugin>:<role>`), the child session
    receives a built-in executor: the role identity is lost, and the subagent
    panel shows the built-in agent instead of the role.
    """
    skill = REPO / "skills" / "task-decomposition" / "SKILL.md"
    if not skill.exists():
        return
    txt = skill.read_text(encoding="utf-8", errors="replace")
    if "agent_name=<role>" not in txt:
        bad("(skill)", "SKILL.md has no agent_name=<role> rule")
    if "task-decomposition:" in txt:
        bad("(skill)", "SKILL.md contains a role call with a plugin prefix")
    # The skill is a procedural reference, not a duplicate of the global contract: keep it
    # concise, without copies of rules 15/18/19.
    size = skill.stat().st_size
    if size > 16384:
        bad("(skill)", "SKILL.md is oversized: %d bytes (16384-byte limit) - duplicates global contract rules" % size)
    # Dynamic Workflow is not used: the official MCode CLI is required; execution is
    # manual in the dashboard, and role selection in ctx.agent is undocumented.
    if re.search(r"(?i)dynamic[ -]?workflow", txt):
        bad("(skill)", "SKILL.md still mentions Dynamic Workflow - the mechanism does not work")
    if "mavis_agent_list" not in txt:
        bad("(skill)", "SKILL.md does not say where to get the role list (mavis_agent_list)")

def check_icons_distinct(agents_dir: Path) -> None:
    """Every role must carry its own icon.

    The icon is the only visual signal of a role zone in the agent picker, so
    identical icons make the roles indistinguishable. The guard also catches a
    stale copy of one generic avatar pasted over all eight roles.
    """
    import hashlib
    seen: dict[str, str] = {}
    for role in sorted(p.name for p in agents_dir.iterdir() if p.is_dir()):
        icon = agents_dir / role / "avatar.png"
        if not icon.exists():
            continue
        digest = hashlib.sha256(icon.read_bytes()).hexdigest()
        if digest in seen:
            bad(role, "avatar.png is identical to the icon of role %s" % seen[digest])
        else:
            seen[digest] = role


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", default=str(PROFILE_AGENTS))
    ap.add_argument("--no-profile", action="store_true",
                    help="do not compare against the profile (repository only)")
    args = ap.parse_args()
    profile_dir = Path(args.profile)
    roles = sorted(p.name for p in AGENTS_DIR.iterdir() if p.is_dir()) if AGENTS_DIR.is_dir() else []
    if not roles:
        print("NO AGENT DIRECTORY:", AGENTS_DIR)
        return 1
    required = expected_roles()
    for role in sorted(required - set(roles)):
        bad("(roles)", "role is registered but has no agent directory: %s" % role)
    for role in sorted(set(roles) - required):
        bad("(roles)", "agent exists but the role is not registered: %s" % role)
    for role in roles:
        check_role(role, AGENTS_DIR, profile_dir if not args.no_profile else AGENTS_DIR)
    check_icons_distinct(AGENTS_DIR)
    check_zone_anchors(AGENTS_DIR)
    check_card_asset_drift(AGENTS_DIR, REPO / "runtime" / "builtin-agents-v2")
    check_skill_channel()
    print("=== check_role_agents: checked %d roles (registered %d) ===" % (len(roles), len(required)))
    if PROBLEMS:
        for p in PROBLEMS:
            print(" -", p)
        print("RESULT: FAIL (%d)" % len(PROBLEMS))
        return 1
    print("RESULT: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
